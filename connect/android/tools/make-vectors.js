#!/usr/bin/env node
// Writes protocol test vectors from the JavaScript implementation (the
// reference) for the Kotlin port's tests: two identities with their keys,
// cards, envelopes sealed by each to the other, a pairing link, inbox
// token, device relay ticket, safety code and valid/invalid messages.
//
//   node connect/android/tools/make-vectors.js
//
// Output: connect/android/app/src/test/resources/vectors.json. Needs the
// desktop engine built (ppkeygen). Regenerate after any protocol change;
// the Kotlin tests then show where the port no longer matches.

const crypto = require("crypto");
const fs = require("fs");
const os = require("os");
const path = require("path");

const repo = path.resolve(__dirname, "..", "..", "..");
const core = require(path.join(repo, "connect", "core"));
const p = require(path.join(repo, "protocol"));

const keygenPath = path.join(repo, "build", "engine", `ppkeygen${process.platform === "win32" ? ".exe" : ""}`);
const tmp = fs.mkdtempSync(path.join(os.tmpdir(), "pp-vectors-"));
const NOW = Date.UTC(2026, 9, 22, 12, 0, 0); // fixed, so time checks are reproducible

function identity(name) {
  const id = core.createIdentity({ dir: path.join(tmp, name), name, keygenPath });

  return {
    id,
    json: {
      name,
      fingerprint: id.fingerprint,
      certDer: id.certDer.toString("base64"),
      certPem: id.certPem,
      keyPem: id.keyPem, // Ed25519 PKCS#8 (ppkeygen's device.key)
      boxPrivatePkcs8: id.boxPrivateKey.export({ format: "der", type: "pkcs8" }).toString("base64"),
      boxPrivateRaw: Buffer.from(id.boxPrivateKey.export({ format: "jwk" }).d, "base64url").toString("base64url"),
      boxPublic: id.boxPublic,
    },
  };
}

const alice = identity("Alice");
const bob = identity("Bob");
const cardOf = (who) => core.verifyCard(core.contactCard(who.id));

const payload = { type: "offer", transferId: "abcdefgh12", files: [{ name: "photo.jpg", size: 1234, files: 1 }], fileCount: 1, totalBytes: 1234 };
const envAliceToBob = core.seal({ identity: alice.id, recipient: cardOf(bob), payload, now: NOW });
const envBobToAlice = core.seal({ identity: bob.id, recipient: cardOf(alice), payload: { type: "pair-accept" }, now: NOW });

const secret = crypto.randomBytes(16).toString("base64url");
const link = p.encodeInviteLink({ identity: alice.id, secret, mailbox: "https://mailbox.example", expiresAt: NOW + 24 * 3600 * 1000 });

const vectors = {
  note: "Generated by connect/android/tools/make-vectors.js from the JavaScript reference. Do not edit.",
  now: NOW,
  alice: alice.json,
  bob: bob.json,
  cards: { alice: core.contactCard(alice.id), bob: core.contactCard(bob.id) },
  safetyCode: core.safetyCode(alice.id.fingerprint, bob.id.fingerprint),
  envelopes: {
    aliceToBob: { envelope: envAliceToBob, payload },
    bobToAlice: { envelope: envBobToAlice, payload: { type: "pair-accept" } },
    tampered: { ...envAliceToBob, ct: envAliceToBob.ct.slice(0, -4) + "AAAA" },
  },
  pairing: { link, secret, mailbox: "https://mailbox.example", expiresAt: Math.floor((NOW + 24 * 3600 * 1000) / 1000) * 1000 },
  inboxToken: { token: p.issueInboxToken(alice.id, { now: NOW, ttlSec: 600 }), verifiedAs: p.verifyInboxToken(p.issueInboxToken(alice.id, { now: NOW, ttlSec: 600 }), NOW) },
  deviceTicket: (() => {
    const ticket = p.issueDeviceTicket({ sessionId: "abcdefgh12", role: "sender", peerFingerprint: bob.id.fingerprint, certPem: alice.id.certPem, keyPem: alice.id.keyPem, ttlSec: 600 }, NOW);

    return { ticket, verifiedAs: p.verifyTicket(ticket, null, NOW) };
  })(),
  messages: {
    valid: [
      payload,
      { type: "accept", transferId: "abcdefgh12", token: "t0ken", port: 40123, addresses: ["192.168.1.7", "::1"], relay: true },
      { type: "decline", transferId: "abcdefgh12" },
      { type: "cancel", transferId: "abcdefgh12", paused: true },
      { type: "cancel", transferId: "abcdefgh12", removed: true },
      { type: "resume-request", transferId: "abcdefgh12" },
      { type: "reverse", transferId: "abcdefgh12", addresses: ["192.168.137.35"], port: 50555, key: "ab".repeat(32) },
      { type: "offer", transferId: "abcdefgh12", files: [], fileCount: 0, totalBytes: 0, resume: true },
      { type: "pair-accept" },
      { type: "pair-request", secret, card: core.contactCard(bob.id), mailbox: "https://mailbox.example" },
    ],
    invalid: [
      { type: "nope", transferId: "abcdefgh12" },
      { type: "decline", transferId: "abc" },
      { type: "accept", transferId: "abcdefgh12", token: "t", port: 0, addresses: ["10.0.0.1"], relay: false },
      { type: "accept", transferId: "abcdefgh12", token: "t", port: 1, addresses: [], relay: false },
      { type: "accept", transferId: "abcdefgh12", token: "t", port: 1, addresses: ["example.com"], relay: false },
      { type: "offer", transferId: "abcdefgh12", files: [], fileCount: 1, totalBytes: -1 },
      { type: "pair-request", secret, card: { ...core.contactCard(bob.id), fp: alice.id.fingerprint } },
    ],
  },
};

// Sanity: the JS side agrees with its own vectors.
for (const m of vectors.messages.valid) if (!p.parseMessage(m)) throw new Error(`valid message rejected: ${JSON.stringify(m)}`);
for (const m of vectors.messages.invalid) if (p.parseMessage(m)) throw new Error(`invalid message accepted: ${JSON.stringify(m)}`);

const out = path.join(__dirname, "..", "app", "src", "test", "resources", "vectors.json");

fs.mkdirSync(path.dirname(out), { recursive: true });
fs.writeFileSync(out, JSON.stringify(vectors, null, 2));
fs.rmSync(tmp, { recursive: true, force: true });
console.log(`wrote ${out}`);
